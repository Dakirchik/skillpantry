"""Render the catalog as one Markdown note (for Obsidian) — manifests stay the source of truth."""

from __future__ import annotations

from collections import defaultdict

from skillpantry.i18n import T
from skillpantry.catalog import (RISK_LABELS, STATUS_LABELS, TARGET_LABELS, TARGETS, Catalog,
                                Entry, today)

MARK = {"auto": "✅", "manual": "🛠", "none": "—"}


def _support_row(e: Entry) -> str:
    return " | ".join(MARK[e.support(t)] for t in TARGETS)


def _payload(e: Entry) -> str:
    parts = []
    if e.skills:
        parts.append(T("skills", "скиллы"))
    if e.rules:
        parts.append(T("rules", "правила"))
    if e.mcp:
        parts.append("MCP")
    if e.commands:
        parts.append(T("commands", "команды"))
    if e.variants:
        parts.append(T("file variant", "файл-вариант"))
    if e.workspace:
        parts.append(T("workspace folder", "рабочая папка"))
    if not parts and e.manual:
        parts.append(T("manual install", "ручная установка"))
    return ", ".join(parts) or "—"


def render(cat: Catalog) -> str:
    entries = cat.sorted()
    L = ["---", "tags: [ai, skills, mcp, skillpantry]", f"updated: {today()}",
         T("source: skillpantry catalog (generated by skillpantry export-md)", "source: skillpantry catalog (сгенерировано командой skillpantry export-md)"), "---", "",
         T("# Catalog of skills, plugins and MCP", "# Каталог скиллов, плагинов и MCP"), "",
         T("> Generated from skillpantry manifests. Edit the manifests and rebuild this file:", "> Сгенерировано из манифестов skillpantry. Править нужно манифесты, а этот файл — пересобрать:"),
         T("> `skillpantry export-md -o <path in the vault>`.", "> `skillpantry export-md -o <путь в vault>`."), "",
         T("Legend: ✅ installed automatically · 🛠 manual steps (skillpantry prints the commands) · — not supported.", "Легенда: ✅ ставится автоматически · 🛠 ручные шаги (команды показывает skillpantry) · — не подходит."), "",
         T("## Index", "## Указатель"), "",
         T("| # | Entry | Status | Risk | Work-safe | ", "| # | Запись | Статус | Риск | Для работы | ") + " | ".join(TARGET_LABELS[t].split(" ")[0]
                                                                for t in TARGETS) + " |",
         "|---|---|---|---|---|" + "---|" * len(TARGETS)]
    for e in entries:
        L.append(T(f"| {e.number} | [[#{e.number}. {e.name}\\|{e.name}]] | {STATUS_LABELS[e.status]} | " f"{RISK_LABELS[e.risk]} | {'yes' if e.work_safe else 'no'} | {_support_row(e)} |", f"| {e.number} | [[#{e.number}. {e.name}\\|{e.name}]] | {STATUS_LABELS[e.status]} | "
                 f"{RISK_LABELS[e.risk]} | {'да' if e.work_safe else 'нет'} | {_support_row(e)} |"))
    by_cat: dict[str, list[Entry]] = defaultdict(list)
    for e in entries:
        by_cat[e.category].append(e)
    L += ["", T("## Entries", "## Записи"), ""]
    for e in entries:
        L += [f"### {e.number}. {e.name}", "", f"**{e.summary}**", ""]
        meta = [f"`{e.id}`", T(f"status: {STATUS_LABELS[e.status]}", f"статус: {STATUS_LABELS[e.status]}"), T(f"risk: {RISK_LABELS[e.risk]}", f"риск: {RISK_LABELS[e.risk]}"),
                T(f"category: {e.category}", f"категория: {e.category}")]
        if e.license:
            meta.append(T(f"license: {e.license}", f"лицензия: {e.license}"))
        L.append("- " + " · ".join(meta))
        if e.repo:
            L.append(T(f"- Source: [{e.repo}]({e.git_url}) @ `{(e.ref or '')[:12]}`", f"- Источник: [{e.repo}]({e.git_url}) @ `{(e.ref or '')[:12]}`")
                     + (T(f" (reviewed {e.reviewed})", f" (проверено {e.reviewed})") if e.reviewed else ""))
        elif e.local:
            L.append(T(f"- Source: own folder `{e.local}`", f"- Источник: своя папка `{e.local}`"))
        elif e.url:
            L.append(T(f"- Link: {e.url}", f"- Ссылка: {e.url}"))
        L.append(T(f"- Installs: {_payload(e)}", f"- Что ставится: {_payload(e)}"))
        if e.description:
            L += ["", e.description]
        if e.risk_notes:
            L += ["", T("Risks:", "Риски:")] + [f"- {n}" for n in e.risk_notes]
        if e.overlaps:
            L += ["", T("Overlaps with: ", "Пересекается с: ") + ", ".join(f"`{o}`" for o in e.overlaps)]
        manual = {t: v for t, v in e.manual.items() if v}
        if manual:
            L += ["", T("Manual steps:", "Ручные шаги:")]
            for t, steps in manual.items():
                who = T("all", "все") if t == "any" else TARGET_LABELS.get(t, t)
                L += [f"- {who}: " + "; ".join(f"`{s}`" for s in steps)]
        if e.installable and e.support("claude-code") == "auto":
            L += ["", T(f"Install: `skillpantry install {e.id} -t claude-code`", f"Установка: `skillpantry install {e.id} -t claude-code`")]
        L.append("")
    L += [T("## By category", "## По категориям"), ""]
    for c in cat.category_order():
        if by_cat.get(c.id):
            L.append(f"- **{c.title}**: " + ", ".join(e.name for e in by_cat[c.id]))
    L.append("")
    return "\n".join(L)
